// Excel and PDF exports of a closed campaign: content, creator-only, refused while open, audited, no formula injection.
import ExcelJS from 'exceljs';
import { afterAll, beforeEach, describe, expect, it } from 'vitest';
import { createApp } from '../../src/app.js';
import { closePool, getPool } from '../../src/db.js';
import { buildPdf, buildXlsx, fmtWindhoek, gatherExport, safeCell } from '../../src/services/resultsExport.js';
import type { CampaignRow } from '../../src/services/campaigns.js';
import { ADMIN_A, ADMIN_B, S1, S2, S3, closeOwner, login, ownerDb, resetDb } from '../helpers.js';

const app = createApp();
beforeEach(resetDb);
afterAll(async () => { await closePool(); await closeOwner(); });

const binary = (res: import('superagent').Response, cb: (err: Error | null, body: Buffer) => void) => {
  const chunks: Buffer[] = []; res.on('data', (c: Buffer) => chunks.push(c)); res.on('end', () => cb(null, Buffer.concat(chunks)));
};
const INJECT = '=HYPERLINK("http://evil.example","click")';

/** A closed campaign: 3 candidates (one named like a formula), 3 votes, an edit after start, then closed. */
async function closedCampaign() {
  const admin = await login(app, ADMIN_A);
  const c = (await admin.post('/api/campaigns').send({ title: 'Staff Council Election', description: 'Pick the chair', eligibility: 'all', allow_edits_after_start: true }).expect(201)).body;
  const cands: string[] = [];
  for (const name of ['Alice Example', INJECT, 'Carol Test']) cands.push((await admin.post(`/api/campaigns/${c.id}/candidates`).field('name', name).expect(201)).body.id);
  await admin.post(`/api/campaigns/${c.id}/start`).expect(200);
  await admin.patch(`/api/campaigns/${c.id}`).send({ title: 'Staff Council Election 2026' }).expect(200);
  const s1 = await login(app, S1); const s2 = await login(app, S2); const s3 = await login(app, S3);
  await s1.post(`/api/vote/${c.share_token}`).send({ candidateId: cands[0] }).expect(201);
  await s2.post(`/api/vote/${c.share_token}`).send({ candidateId: cands[0] }).expect(201);
  await s3.post(`/api/vote/${c.share_token}`).send({ candidateId: cands[2] }).expect(201);
  await admin.post(`/api/campaigns/${c.id}/close`).send({}).expect(200);
  return { admin, id: c.id as string, token: c.share_token as string };
}
const load = async (buf: Buffer) => { const wb = new ExcelJS.Workbook(); await wb.xlsx.load(buf as never); return wb; };
const sheetText = (ws: ExcelJS.Worksheet) => { const out: string[] = []; ws.eachRow((r) => r.eachCell((c) => out.push(String(c.value ?? '')))); return out.join('\n'); };
/** Text shown by an UNcompressed pdfkit document: its strings are hex-encoded in the TJ operators. */
const pdfText = (buf: Buffer) => [...buf.toString('latin1').matchAll(/\[([^\]]*)\]\s*TJ/g)]
  .map((m) => [...m[1].matchAll(/<([0-9a-f]*)>/g)].map((h) => Buffer.from(h[1], 'hex').toString('latin1')).join('')).join('\n');

describe('GET /api/campaigns/:id/results.xlsx', () => {
  it('is a real workbook with the campaign, times, eligibility, turnout, per-candidate votes and %, tie flag, history, seal and who/when', async () => {
    const { admin, id } = await closedCampaign();
    const res = await admin.get(`/api/campaigns/${id}/results.xlsx`).buffer(true).parse(binary).expect(200);
    expect(res.headers['content-type']).toContain('spreadsheetml.sheet');
    expect(res.headers['content-disposition']).toContain('results.xlsx');
    expect(res.headers['cache-control']).toContain('no-store');
    const wb = await load(res.body as Buffer);
    expect(wb.worksheets.map((w) => w.name)).toEqual(['Summary', 'Results', 'Event history']);

    const summary = sheetText(wb.getWorksheet('Summary')!);
    expect(summary).toContain('Staff Council Election 2026');       // the title as it is now (it was edited after start)
    expect(summary).toContain('Pick the chair');
    expect(summary).toMatch(/\d{2} \w{3} \d{4}, \d{2}:\d{2} CAT/);  // Windhoek time, labelled
    expect(summary).toContain('All staff');
    expect(summary).toContain('n/a (open to all staff)');            // no eligible count exists for "all"
    expect(summary).toContain(ADMIN_A.email);                        // generated by
    expect(summary).toContain('Generated at');
    const seal = (await ownerDb().query("SELECT hash FROM audit_log WHERE campaign_id = $1 AND action LIKE 'campaign.close%' ORDER BY seq DESC LIMIT 1", [id])).rows[0].hash;
    expect(summary).toContain(seal);                                 // the fingerprint of the sealed audit entry
    expect(summary).toContain('counters and receipts match the seal');
    const turnoutRow = wb.getWorksheet('Summary')!.getRows(1, 30)!.find((r) => r.getCell(1).value === 'Turnout (votes cast)')!;
    expect(turnoutRow.getCell(2).value).toBe(3);

    const rs = wb.getWorksheet('Results')!;
    const rows = [2, 3, 4].map((n) => rs.getRow(n).values as unknown[]);
    expect(rows[0]).toEqual([undefined, 1, 'Alice Example', 2, 2 / 3]);
    expect(rows.map((r) => r[3])).toEqual([2, 1, 0]);
    expect(rows[1][4]).toBeCloseTo(1 / 3, 5);
    expect(sheetText(wb.getWorksheet('Summary')!)).toContain('No (leader: Alice Example)');

    const hist = sheetText(wb.getWorksheet('Event history')!);
    expect(hist).toContain('Edited after start');
    expect(hist).toContain('title changed from "Staff Council Election" to "Staff Council Election 2026"');
  });

  it('flags a tie', async () => {
    const admin = await login(app, ADMIN_A);
    const c = (await admin.post('/api/campaigns').send({ title: 'Tie', eligibility: 'all' }).expect(201)).body;
    const cands: string[] = [];
    for (const n of ['One', 'Two']) cands.push((await admin.post(`/api/campaigns/${c.id}/candidates`).field('name', n).expect(201)).body.id);
    await admin.post(`/api/campaigns/${c.id}/start`).expect(200);
    await (await login(app, S1)).post(`/api/vote/${c.share_token}`).send({ candidateId: cands[0] }).expect(201);
    await (await login(app, S2)).post(`/api/vote/${c.share_token}`).send({ candidateId: cands[1] }).expect(201);
    await admin.post(`/api/campaigns/${c.id}/close`).send({}).expect(200);
    const res = await admin.get(`/api/campaigns/${c.id}/results.xlsx`).buffer(true).parse(binary).expect(200);
    expect(sheetText((await load(res.body as Buffer)).getWorksheet('Summary')!)).toContain('YES: tie between One, Two');
  });

  it('formula injection: a candidate called =HYPERLINK(...) is stored as text, never as a formula', async () => {
    const { admin, id } = await closedCampaign();
    const res = await admin.get(`/api/campaigns/${id}/results.xlsx`).buffer(true).parse(binary).expect(200);
    const wb = await load(res.body as Buffer);
    const hit: ExcelJS.Cell[] = [];
    for (const ws of wb.worksheets) ws.eachRow((r) => r.eachCell((c) => { if (String(c.value).includes('HYPERLINK')) hit.push(c); }));
    expect(hit.length).toBeGreaterThan(0);
    for (const c of hit) {
      expect(c.type).toBe(ExcelJS.ValueType.String);                      // not a Formula cell
      expect((c as unknown as { formula?: string }).formula).toBeUndefined();
      expect(String(c.value).startsWith("'=")).toBe(true);                // neutralised, same as the CSV export
    }
    for (const ws of wb.worksheets) ws.eachRow((r) => r.eachCell((c) => { expect(c.type).not.toBe(ExcelJS.ValueType.Formula); }));
  });
});

describe('GET /api/campaigns/:id/results.pdf', () => {
  it('is a PDF that is served as an attachment', async () => {
    const { admin, id } = await closedCampaign();
    const res = await admin.get(`/api/campaigns/${id}/results.pdf`).buffer(true).parse(binary).expect(200);
    expect(res.headers['content-type']).toContain('application/pdf');
    expect(res.headers['content-disposition']).toContain('results.pdf');
    expect((res.body as Buffer).subarray(0, 5).toString()).toBe('%PDF-');
  });

  it('carries the header text, campaign details, results, history, seal fingerprint and who/when', async () => {
    const { id } = await closedCampaign();
    const row = (await ownerDb().query('SELECT * FROM campaigns WHERE id = $1', [id])).rows[0] as CampaignRow;
    const data = await gatherExport(getPool(), row, `Alice Admin (${ADMIN_A.email})`);
    const text = pdfText(await buildPdf(data, { compress: false }));
    for (const want of ['NamRA | Voting', 'Staff Council Election 2026', 'Pick the chair', 'All staff', 'Alice Example', 'Carol Test', '66.7%', '33.3%', 'Total votes',
      'Edited after start', 'title changed from', 'Generated', ADMIN_A.email, 'Windhoek time', 'CAT']) expect(text).toContain(want);
    const seal = (await ownerDb().query("SELECT hash FROM audit_log WHERE campaign_id = $1 AND action LIKE 'campaign.close%' ORDER BY seq DESC LIMIT 1", [id])).rows[0].hash as string;
    expect(text).toContain(seal);
  });
});

describe('who may export, and when', () => {
  it('refuses an OPEN campaign for both formats (SEC-01), and a draft', async () => {
    const admin = await login(app, ADMIN_A);
    const c = (await admin.post('/api/campaigns').send({ title: 'Open', eligibility: 'all' }).expect(201)).body;
    for (const n of ['A', 'B']) await admin.post(`/api/campaigns/${c.id}/candidates`).field('name', n).expect(201);
    for (const f of ['xlsx', 'pdf']) await admin.get(`/api/campaigns/${c.id}/results.${f}`).expect(409);
    await admin.post(`/api/campaigns/${c.id}/start`).expect(200);
    await (await login(app, S1)).post(`/api/vote/${c.share_token}`).send({ candidateId: (await admin.get(`/api/campaigns/${c.id}`)).body.candidates[0].id }).expect(201);
    for (const f of ['xlsx', 'pdf']) {
      const r = await admin.get(`/api/campaigns/${c.id}/results.${f}`).expect(409);
      expect(r.body.code).toBe('not_closed');
      expect(JSON.stringify(r.body)).not.toMatch(/votes|Candidate/i);
    }
    expect((await ownerDb().query("SELECT count(*)::int AS n FROM audit_log WHERE action IN ('results.export_xlsx','results.export_pdf')")).rows[0].n).toBe(0);
  });

  it('only the creator: another admin gets 404, staff 403, anonymous gets 401, and nothing is audited', async () => {
    const { id } = await closedCampaign();
    const other = await login(app, ADMIN_B); const staff = await login(app, S1);
    for (const f of ['xlsx', 'pdf']) {
      await other.get(`/api/campaigns/${id}/results.${f}`).expect(404);
      await staff.get(`/api/campaigns/${id}/results.${f}`).expect(403);
    }
    const anon = await (await import('supertest')).default(app).get(`/api/campaigns/${id}/results.xlsx`);
    expect(anon.status).toBe(401);
    expect((await ownerDb().query("SELECT count(*)::int AS n FROM audit_log WHERE action IN ('results.export_xlsx','results.export_pdf')")).rows[0].n).toBe(0);
  });

  it('each export is audited with the actor, and counts as the copy needed before a permanent delete', async () => {
    const { admin, id } = await closedCampaign();
    await admin.get(`/api/campaigns/${id}/results.xlsx`).expect(200);
    await admin.get(`/api/campaigns/${id}/results.pdf`).expect(200);
    const rows = (await ownerDb().query("SELECT action, actor_oid, details FROM audit_log WHERE campaign_id = $1 AND action LIKE 'results.export_%' ORDER BY seq", [id])).rows;
    expect(rows.map((r) => r.action)).toEqual(['results.export_xlsx', 'results.export_pdf']);
    expect(rows.every((r) => r.actor_oid === ADMIN_A.oid)).toBe(true);
    expect(JSON.stringify(rows)).not.toMatch(/Alice Example|candidate/i);       // the entry says that it happened, not what was in it
    await admin.post(`/api/campaigns/${id}/archive`).send({}).expect(200);
    await admin.post(`/api/campaigns/${id}/permanent-delete`).send({ confirm_title: 'Staff Council Election 2026' }).expect(200);
  });
});

describe('helpers', () => {
  it('safeCell neutralises formula starters, also behind spaces or control characters, and leaves normal text alone', () => {
    for (const bad of ['=1+1', '+1', '-1', '@SUM(A1)', '  =A1', '\t=A1', '\r=A1']) expect(safeCell(bad)).toBe("'" + bad);
    for (const ok of ['Alice', 'A=B', 'Dr. -X', '', '12 Nov']) expect(safeCell(ok)).toBe(ok);
    expect(safeCell(null)).toBe('');
  });

  it('times are Windhoek time (CAT, UTC+2) whatever the server zone is', () => {
    expect(fmtWindhoek('2026-11-12T07:30:00Z')).toBe('12 Nov 2026, 09:30 CAT');
    expect(fmtWindhoek(null)).toBe('Not set');
  });

  it('buildXlsx never writes a user string as a formula even when given one directly', async () => {
    const wb = await load(await buildXlsx({
      title: '=cmd|calc', description: '@x', status: 'closed', opensAt: 'a', closesAt: 'b', startedAt: 'c', closedAt: 'd', eligibility: 'All staff', eligibleCount: null,
      turnout: 1, turnoutPct: null, candidates: [{ rank: 1, name: '+SUM(1)', votes: 1, pct: 1 }], tie: false, tiedNames: [], leader: '+SUM(1)', runoff: '', abstentions: null, withdrawn: [], quorum: '', publication: '',
      history: [{ kind: 'Reset', at: 't', by: '-bob', detail: '=evil' }], seal: { sealed: false, hash: null, sealedAt: 'Not set', verified: null }, generatedAt: 'g', generatedBy: '=me',
    }));
    for (const ws of wb.worksheets) ws.eachRow((r) => r.eachCell((c) => { expect(c.type).not.toBe(ExcelJS.ValueType.Formula); }));
    expect(sheetText(wb.getWorksheet('Summary')!)).toContain("'=cmd|calc");
    expect(sheetText(wb.getWorksheet('Results')!)).toContain("'+SUM(1)");
    expect(sheetText(wb.getWorksheet('Event history')!)).toContain("'=evil");
  });
});
